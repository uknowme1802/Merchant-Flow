const TAG = {
  merchant: "bg-indigo-50 text-indigo-700",
  user: "bg-sky-50 text-sky-700",
  bank: "bg-emerald-50 text-emerald-700",
  credential: "bg-amber-50 text-amber-700",
  team: "bg-gray-100 text-gray-700"
}

const ACTORS = { admin: "Admin", merchant_user: "Merchant user", merchant_api: "Merchant API", anonymous: "Anonymous", system: "System" }

const actionLabel = (action) => ACTIONS[action] || action.replace(/[._]/g, " ")
const words = (key) => key.replace(/([a-z])([A-Z])/g, "$1 $2").replace(/_/g, " ").toLowerCase()
const show = (value) => {
  if (value === null || value === undefined || value === "") return "-"
  if (typeof value === "boolean") return value ? "yes" : "no"
  if (Array.isArray(value)) return value.join(", ") || "-"
  if (typeof value === "object") return Object.entries(value).map(([k, v]) => `${words(k)} ${show(v)}`).join(", ")
  return String(value)
}

// Turns an entry's metadata into readable lines: "payin bps: 0 → 250", "reason: chargeback spike".
// The MID is left out because it has its own column.
const detailLines = (metadata = {}) => {
  const { before, after, mid: _mid, ...rest } = metadata || {}
  const lines = []
  if (after && typeof after === "object") {
    for (const key of Object.keys(after)) {
      if (show(before?.[key]) !== show(after[key])) lines.push(`${words(key)}: ${show(before?.[key])} → ${show(after[key])}`)
    }
  }
  if (rest.from !== undefined && rest.to !== undefined) {
    lines.push(`${show(rest.from)} → ${show(rest.to)}`)
    delete rest.from
    delete rest.to
  }
  for (const [key, value] of Object.entries(rest)) {
    if (value !== null && value !== undefined && value !== "") lines.push(`${words(key)}: ${show(value)}`)
  }
  return lines
}

const targetOf = (log) => log.mid || log.metadata?.email || log.metadata?.username || log.metadata?.bankId || null

function Details({ lines }) {
  const [open, setOpen] = useState(false)
  if (!lines.length) return <span className="text-gray-400">-</span>

  const visible = open ? lines : lines.slice(0, 2)
  return (
    <div className="space-y-0.5">
      {visible.map((line) => <div key={line} className="break-words">{line}</div>)}
      {lines.length > 2 && (
        <button type="button" onClick={() => setOpen(!open)} className="p-0 text-xs font-normal text-indigo-600 hover:underline">
          {open ? "Show less" : `Show ${lines.length - 2} more`}
        </button>
      )}
    </div>
  )
}

// The platform audit trail as a table: when, what, who, on what, and the details of the change.
export default function AuditLogTable() {
  const [action, setAction] = useState("")
  const [page, setPage] = useState(1)
  const [limit, setLimit] = useState(25)
  const [result, setResult] = useState({ data: [], total: 0 })

  useEffect(() => {
    let ignore = false
    API.get("/admin/audit-logs", { params: { action: action || undefined, page, limit } })
      .then((res) => { if (!ignore) setResult({ data: res.data.data, total: res.data.total }) })
      .catch(() => {})
    return () => { ignore = true }
  }, [action, page, limit])

  return (
    <>
      <div className="flex items-center gap-3">
        <select className="px-3 py-2 rounded-xl bg-white text-sm ring-1 ring-gray-200 shadow-sm focus:outline-none focus:ring-2 focus:ring-indigo-300" aria-label="Action" value={action}
          onChange={(e) => { setAction(e.target.value); setPage(1) }}>
          <option value="">All actions</option>
          {Object.entries(ACTIONS).map(([value, label]) => <option key={value} value={value}>{label}</option>)}
        </select>
      </div>

      <Card>
        <div className="overflow-x-auto">
          <table className="data-table">
            <thead>
              <tr>
                <th className="pr-4">Time</th>
                <th className="pr-4">Action</th>
                <th className="pr-4">By</th>
                <th className="pr-4">Target</th>
                <th>Details</th>
              </tr>
            </thead>
            <tbody>
              {result.data.length === 0 && (
                <tr><td colSpan={5} className="py-6 text-center text-gray-500">No audit entries found.</td></tr>
              )}
              {result.data.map((log) => (
                <tr key={log.id} className="align-top">
                  <td className="py-3 pr-4 whitespace-nowrap text-gray-600">{formatIST(log.createdAt)}</td>
                  <td className="py-3 pr-4 whitespace-nowrap">
                    <span className={`px-2 py-1 rounded text-xs font-semibold ${TAG[log.action.split(".")[0]] || TAG.team}`}>
                      {actionLabel(log.action)}
                    </span>
                  </td>
                  <td className="py-3 pr-4">
                    <span className="block">{ACTORS[log.actorType] || log.actorType}</span>
                    {log.actorEmail && <span className="block text-xs text-gray-500">{log.actorEmail}</span>}
                  </td>
                  <td className="py-3 pr-4">
                    {targetOf(log) ? <code className="text-xs">{targetOf(log)}</code> : <span className="text-gray-400">-</span>}
                  </td>
                  <td className="py-3 text-gray-600 max-w-md"><Details lines={detailLines(log.metadata)} /></td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>

        <Pagination
          page={page} setPage={setPage} totalPages={Math.ceil(result.total / limit)}
          pageSize={limit} setPageSize={(n) => { setLimit(n); setPage(1) }} total={result.total} sizes={[25, 50, 100]}
        />
      </Card>
    </>
  )
}
